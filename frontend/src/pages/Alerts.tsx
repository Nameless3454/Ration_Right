import React, { useState } from 'react';
import { ShieldAlert, AlertTriangle, AlertCircle, CheckCircle, Search } from 'lucide-react';
import { StatusBadge } from '../components/StatusBadge';
import { mockAlerts } from '../data/mockData';

export const Alerts: React.FC = () => {
  const [activeTab, setActiveTab] = useState<'All' | 'Critical' | 'High' | 'Medium' | 'Low'>('All');
  const [search, setSearch] = useState('');

  const filteredAlerts = mockAlerts.filter(a => {
    const matchesTab = activeTab === 'All' || a.severity === activeTab;
    const matchesSearch = a.title.toLowerCase().includes(search.toLowerCase()) ||
                          a.fps.toLowerCase().includes(search.toLowerCase()) ||
                          a.district.toLowerCase().includes(search.toLowerCase());
    return matchesTab && matchesSearch;
  });

  return (
    <div className="space-y-6">
      {/* Header */}
      <div>
        <h1 className="text-xl md:text-2xl font-bold text-slate-800 tracking-tight">Active Alerts</h1>
        <p className="text-xs md:text-sm text-slate-500 mt-1">
          Review and audit system alerts generated by AI and policy violations.
        </p>
      </div>

      {/* Stats row */}
      <div className="grid grid-cols-2 md:grid-cols-4 gap-4">
        <div className="bg-white border border-slate-200 rounded-lg p-4 flex items-center justify-between">
          <div>
            <span className="text-[10px] text-slate-400 font-bold block uppercase">Critical</span>
            <span className="text-lg font-bold text-red-600">148</span>
          </div>
          <ShieldAlert size={20} className="text-red-500" />
        </div>

        <div className="bg-white border border-slate-200 rounded-lg p-4 flex items-center justify-between">
          <div>
            <span className="text-[10px] text-slate-400 font-bold block uppercase">High</span>
            <span className="text-lg font-bold text-red-500">290</span>
          </div>
          <AlertTriangle size={20} className="text-red-400" />
        </div>

        <div className="bg-white border border-slate-200 rounded-lg p-4 flex items-center justify-between">
          <div>
            <span className="text-[10px] text-slate-400 font-bold block uppercase">Medium</span>
            <span className="text-lg font-bold text-orange-500">98</span>
          </div>
          <AlertCircle size={20} className="text-orange-400" />
        </div>

        <div className="bg-white border border-slate-200 rounded-lg p-4 flex items-center justify-between">
          <div>
            <span className="text-[10px] text-slate-400 font-bold block uppercase">Low</span>
            <span className="text-lg font-bold text-green-600">47</span>
          </div>
          <CheckCircle size={20} className="text-green-500" />
        </div>
      </div>

      {/* Tabs and search bar */}
      <div className="bg-white border border-slate-200 rounded-lg p-4 flex flex-col md:flex-row md:items-center justify-between gap-4">
        {/* Severity Tabs */}
        <div className="flex gap-1.5 border-b border-slate-100 md:border-b-0 pb-2 md:pb-0 overflow-x-auto">
          {(['All', 'Critical', 'High', 'Medium', 'Low'] as const).map((tab) => (
            <button
              key={tab}
              onClick={() => setActiveTab(tab)}
              className={`px-3 py-1.5 rounded text-xs font-semibold whitespace-nowrap transition-colors ${
                activeTab === tab 
                  ? 'bg-[#E0F2FE] text-[#0369A1]' 
                  : 'text-slate-500 hover:bg-slate-50 hover:text-slate-800'
              }`}
            >
              {tab}
            </button>
          ))}
        </div>

        {/* Search */}
        <div className="relative w-full md:w-64">
          <Search size={14} className="absolute left-3 top-1/2 -translate-y-1/2 text-slate-400" />
          <input
            type="text"
            placeholder="Search alerts..."
            value={search}
            onChange={(e) => setSearch(e.target.value)}
            className="w-full h-8 pl-9 pr-4 border border-slate-200 rounded text-xs focus:outline-none focus:border-sky-500 text-slate-700"
          />
        </div>
      </div>

      {/* Alerts Table */}
      <div className="bg-white border border-slate-200 rounded-lg p-5">
        <div className="overflow-x-auto border border-slate-100 rounded-lg">
          <table className="w-full text-left border-collapse text-xs md:text-sm">
            <thead>
              <tr className="bg-slate-50 border-b border-slate-100 text-slate-500 font-semibold tracking-wider text-[10px] uppercase">
                <th className="py-3 px-4 font-bold">Alert ID</th>
                <th className="py-3 px-4 font-bold">Title</th>
                <th className="py-3 px-4 font-bold">Severity</th>
                <th className="py-3 px-4 font-bold">District</th>
                <th className="py-3 px-4 font-bold">FPS Center</th>
                <th className="py-3 px-4 font-bold">Status</th>
                <th className="py-3 px-4 font-bold">Timestamp</th>
              </tr>
            </thead>
            <tbody>
              {filteredAlerts.map((a) => (
                <tr key={a.id} className="border-b border-slate-50 hover:bg-slate-50/70 transition-colors text-slate-700">
                  <td className="py-3 px-4 font-mono font-bold text-slate-500">{a.id}</td>
                  <td className="py-3 px-4">
                    <div>
                      <div className="font-semibold text-slate-800">{a.title}</div>
                      <div className="text-[10px] text-slate-400 mt-0.5">{a.description}</div>
                    </div>
                  </td>
                  <td className="py-3 px-4">
                    <StatusBadge type={a.severity} text={a.severity} />
                  </td>
                  <td className="py-3 px-4 font-medium text-slate-800">{a.district}</td>
                  <td className="py-3 px-4 font-mono text-xs">{a.fps}</td>
                  <td className="py-3 px-4">
                    <StatusBadge type={a.status} text={a.status} />
                  </td>
                  <td className="py-3 px-4 text-xs text-slate-400">{a.createdAt}</td>
                </tr>
              ))}
              {filteredAlerts.length === 0 && (
                <tr>
                  <td colSpan={7} className="py-6 text-center text-xs text-slate-400">No active alerts matching parameters found.</td>
                </tr>
              )}
            </tbody>
          </table>
        </div>
      </div>
    </div>
  );
};
